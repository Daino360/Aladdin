#!/usr/bin/env python3
"""
Evaluate SB3 policy weights (.zip) *inside* the Genie/GenieRedux world model (closed loop).

- Actions are chosen by the SB3 policy from the current WM frame.
- Next frame is generated by the WM (Genie).
- Reward = your FLOW-odometry goal progress (same math as in training script).
- Outputs: GIF + PNG per episode, CSV with episode returns.

Example:
python eval_ppo_in_genie_wm.py \
  --config path/to/world_model.yaml \
  --model_ckpt path/to/world_model.pth \
  --ppo_zip path/to/ppo_agent.zip \
  --init_npz_glob "dataset/*.npz" \
  --episodes 10 --max_steps 256 \
  --save_root runs_wm_eval \
  --dataset_name coinrun \
  --model_name GenieRedux_Guided_CoinRun_80mln_v1.0 \
  --transpose_nchw \
  --goal_screens 1.0 --goal_radius 0.05

"""

